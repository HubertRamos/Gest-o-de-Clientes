export function formatDateTime(iso: string | null | undefined): string {
  if (!iso) return '—';
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return '—';
  return new Intl.DateTimeFormat('pt-BR', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
  }).format(date);
}

export function renderTemplatePreview(content: string, clientName: string): string {
  return content.replace(/\{\{\s*nome\s*\}\}/gi, clientName.trim() || 'Cliente');
}
